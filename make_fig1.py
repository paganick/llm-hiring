"""Fig. 1: concept figure (one candidate, eleven letters, nine blind screeners, different scores).

Writes paper/pipeline_diagram.tex (TikZ, drawn at print size, 170 mm wide) from the
cover-letter-only relative preference gap matrix saved by aggregate_plots.py, so the
dots in Fig. 1 are the same numbers as Fig. 2a. Build the PDF with xelatex:
    python make_fig1.py && cd ../paper && xelatex pipeline_diagram.tex \
        && cp pipeline_diagram.pdf figures/pipeline_diagram.pdf
Model colours = MODEL_SHADES in paper_style.py.
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(HERE, "output_plots", "paper_plots") + os.sep
OUT = os.path.join(HERE, "..", "paper", "pipeline_diagram.tex")
PRE = r"""% Figure 1 (fig:pipeline). GENERATED by code/make_fig1.py from the Fig. 2 data
% (output_plots/paper_plots/heatmap_gap_combined_cl_evaluations.csv) -- edit the script, not this file.
% Build: xelatex pipeline_diagram.tex && cp pipeline_diagram.pdf figures/pipeline_diagram.pdf
\documentclass{article}
\usepackage[paperwidth=171mm,paperheight=61mm,margin=0.5mm]{geometry}
\pagestyle{empty}
\usepackage{tikz}
\setlength{\parindent}{0pt}
\usepackage{fontspec}
\setsansfont{Helvetica}
\renewcommand{\familydefault}{\sfdefault}
\usetikzlibrary{positioning,arrows.meta,calc,fit,backgrounds}

\definecolor{ink}{HTML}{1A1A19}
\definecolor{ink2}{HTML}{52514E}
\definecolor{muted}{HTML}{9A9893}
\definecolor{rule}{HTML}{D9D7D2}
\definecolor{panel}{HTML}{F6F5F2}
\definecolor{fav}{HTML}{A8341F}
\definecolor{penc}{HTML}{2C5D8F}
\definecolor{favbg}{HTML}{FBF1EC}
\definecolor{penbg}{HTML}{EEF3F8}

\definecolor{mGPTfive}{HTML}{1B4F8F}
\definecolor{mGPTfivemini}{HTML}{2A78D6}
\definecolor{mGPTfouromini}{HTML}{4F93E0}
\definecolor{mGemThreeFive}{HTML}{0E7A54}
\definecolor{mGemThree}{HTML}{17A06F}
\definecolor{mSonnet}{HTML}{B54613}
\definecolor{mHaiku}{HTML}{E2622B}
\definecolor{mDSVThree}{HTML}{8E2860}
\definecolor{mDSVFour}{HTML}{C03A83}
\definecolor{mLlama}{HTML}{3A3936}
\definecolor{mRone}{HTML}{77756F}

"""
STY = r"""  every node/.style={inner sep=0pt, outer sep=0pt, text=ink},
  panelbg/.style={fill=panel, rounded corners=2mm, draw=none},
  head/.style={font=\fontsize{7.5pt}{9pt}\selectfont\bfseries, anchor=west},
  num/.style={circle, fill=ink, text=white, minimum size=3.6mm, font=\fontsize{6pt}{6pt}\selectfont\bfseries},
  box/.style={fill=white, draw=rule, rounded corners=1mm, minimum height=7mm, align=center, line width=0.4pt},
  chip/.style={rounded corners=0.8mm, minimum width=16.4mm, minimum height=3.9mm,
               text=white, font=\fontsize{4.7pt}{5pt}\selectfont\bfseries},
  localchip/.style={chip, draw=white, dash pattern=on 0.8pt off 0.6pt, line width=0.5pt},
  arr/.style={-{Stealth[length=1.8mm,width=1.4mm]}, line width=0.6pt, draw=ink2},
  small/.style={font=\fontsize{5.5pt}{6.6pt}\selectfont, text=ink2},
  tiny/.style={font=\fontsize{4.9pt}{5.9pt}\selectfont, text=muted},
  finding/.style={fill=white, draw=rule, rounded corners=1mm, line width=0.4pt,
                  minimum width=50mm, minimum height=10.2mm},
  figtag/.style={fill=panel, rounded corners=0.6mm, inner xsep=1mm, inner ysep=0.6mm,
                 font=\fontsize{5pt}{5pt}\selectfont\bfseries, text=ink2},
"""

def doc(h, body):
    return (PRE.replace("paperheight=61mm", f"paperheight={h}mm") + "\\begin{document}\n\\fontsize{6.5pt}{7.8pt}\\selectfont\n"
            "\\begin{tikzpicture}[x=1mm,y=1mm,\n" + STY + "]\n" + body + "\\end{tikzpicture}\n\\end{document}\n")
TEX = {"gemini-3.5-flash": "mGemThreeFive", "gpt-4o-mini": "mGPTfouromini", "gemini-3-flash-preview": "mGemThree",
       "deepseek-v3.2": "mDSVThree", "claude-4.6-sonnet": "mSonnet", "deepseek-v4-flash": "mDSVFour",
       "gpt-5-mini": "mGPTfivemini", "gpt-5": "mGPTfive", "claude-haiku-4-5": "mHaiku",
       "deepseek-r1-8b": "mRone", "llama3.1-8b": "mLlama"}
NAME = {"gemini-3.5-flash": "Gemini 3.5 Flash", "gpt-4o-mini": "GPT-4o mini", "gemini-3-flash-preview": "Gemini 3 Flash",
        "deepseek-v3.2": "DeepSeek V3.2", "claude-4.6-sonnet": "Claude Sonnet 4.6", "deepseek-v4-flash": "DeepSeek V4 Flash",
        "gpt-5-mini": "GPT-5 mini", "gpt-5": "GPT-5", "claude-haiku-4-5": "Claude Haiku 4.5",
        "deepseek-r1-8b": "DeepSeek R1 8B", "llama3.1-8b": "Llama 3.1 8B"}
LOCAL = {"deepseek-r1-8b", "llama3.1-8b"}
cl = pd.read_csv(P + "heatmap_gap_combined_cl_evaluations.csv", index_col=0)
cv = pd.read_csv(P + "heatmap_gap_combined_cv_cl_evaluations.csv", index_col=0)
avg_cl, avg_cv = cl.loc["Avg."], cv.loc["Avg."]
order = list(avg_cl.sort_values(ascending=False).index)
EVALS = [e for e in cl.index if e != "Avg."]

def cv_icon(x, y, s=1.0):
    return (f"\\begin{{scope}}[shift={{({x},{y})}}, scale={s}]\n"
            "\\fill[white, draw=rule, line width=0.5pt, rounded corners=0.6mm] (-6,-8.5) rectangle (6,8.5);\n"
            "\\fill[ink2] (-4,6) rectangle (0.5,4.9);\n"
            "\\foreach \\yy in {3,1.4,-0.2,-1.8,-3.4,-5}{ \\fill[rule] (-4,\\yy) rectangle (4,\\yy-0.6); }\n\\end{scope}\n")

def letters(y0, dy, xcv=10, ycv=None, xl=24.5, fan=True):
    out = ""
    ycv = ycv if ycv is not None else y0 - dy * 5
    for k, w in enumerate(order):
        y = y0 - k * dy; c = TEX[w]
        dash = ", dash pattern=on 0.7pt off 0.5pt" if w in LOCAL else ""
        if fan:
            out += f"\\draw[ink2!55, line width=0.35pt] ({xcv+6.5},{ycv:.2f}) .. controls ({xcv+10},{ycv:.2f}) and ({xl-3.5},{y:.2f}) .. ({xl-0.3},{y:.2f});\n"
        out += f"\\fill[{c}, rounded corners=0.4mm] ({xl},{y+1.5:.2f}) rectangle ({xl+2.7},{y-1.5:.2f});\n"
        if dash:
            out += f"\\draw[white, line width=0.45pt, rounded corners=0.4mm{dash}] ({xl},{y+1.5:.2f}) rectangle ({xl+2.7},{y-1.5:.2f});\n"
        out += f"\\node[anchor=west, font=\\fontsize{{5.4pt}}{{6pt}}\\selectfont, text={c}] at ({xl+3.8},{y:.2f}) {{{NAME[w]}}};\n"
    return out

def screener(x, y, w=17, h=22):
    out = f"\\node[box, minimum width={w}mm, minimum height={h}mm] at ({x},{y}) {{}};\n"
    for i, e in enumerate(EVALS):
        out += f"\\fill[{TEX[e]}] ({x-3.6+(i%3)*3.6:.2f},{y+7.4-(i//3)*3.6:.2f}) circle (1.15);\n"
    out += (f"\\node[small, align=center, text=ink] at ({x},{y-6}) {{\\textbf{{9 LLM}}\\\\\\textbf{{screeners}}\\\\[0.3mm]"
            "{\\color{ink2}blind to}\\\\{\\color{ink2}the writer}};\n")
    return out

def bars(xb, y0, dy, vals, s, h=1.2, lab=True, alpha=75, dx=0.0):
    out = ""
    for k, w in enumerate(order):
        g = vals[w]; y = y0 - k * dy + dx
        out += f"\\fill[{'fav' if g > 0 else 'penc'}!{alpha}] ({xb:.2f},{y+h:.2f}) rectangle ({xb+g*s:.2f},{y-h:.2f});\n"
        if lab:
            out += (f"\\node[anchor={'west' if g >= 0 else 'east'}, font=\\fontsize{{4.8pt}}{{5pt}}\\selectfont, text=ink2] "
                    f"at ({xb+g*s+(0.8 if g >= 0 else -0.8):.2f},{y:.2f}) {{{g:+.2f}}};\n")
    return out

FIND = [("Writer-preference hierarchy", "small local models rank last", "Fig. 2"),
        ("Evaluator bias", "evaluators differ in bias added", "Fig. 3"),
        ("Hiring consequences", "$\\approx$2 of 25 high-fit displaced", "Fig. 4"),
        ("Style explains it", "a few writing features", "Fig. 5"),
        ("Self-preference", "weaker, not tied to being liked", "Fig. 6")]
def findings_col(x0=117, top=-20.2, step=7.8, h=7.0):
    out = ""
    for k, (t, a, f) in enumerate(FIND):
        y = top - k * step
        out += (f"\\node[finding, minimum width=49mm, minimum height={h}mm] at ({x0+26.5},{y:.2f}) {{}};\n"
                f"\\node[anchor=west, font=\\fontsize{{6pt}}{{7pt}}\\selectfont\\bfseries] at ({x0+4},{y+1.5:.2f}) {{{t}}};\n"
                f"\\node[figtag, anchor=east] at ({x0+49.5},{y+1.5:.2f}) {{{f}}};\n"
                f"\\node[anchor=west, small] at ({x0+4},{y-1.6:.2f}) {{{a}}};\n")
    return out
def findings_row(y, x0=0, W=170, gap=2):
    out = ""; w = (W - 3 * gap) / 4
    for k, (t, a, f) in enumerate(FIND):
        xl = x0 + k * (w + gap)
        out += (f"\\node[finding, minimum width={w}mm, minimum height=8.6mm] at ({xl+w/2:.2f},{y}) {{}};\n"
                f"\\node[anchor=west, font=\\fontsize{{6pt}}{{7pt}}\\selectfont\\bfseries] at ({xl+2.2:.2f},{y+1.8}) {{{t}}};\n"
                f"\\node[figtag, anchor=east] at ({xl+w-1.6:.2f},{y+1.8}) {{{f}}};\n"
                f"\\node[anchor=west, small] at ({xl+2.2:.2f},{y-1.9}) {{{a}}};\n")
    return out


# ---------- C2: per-evaluator dots (as Fig. 2) ----------
b = "\\fill[panel, rounded corners=2mm] (0,0) rectangle (113,-60);\n\\fill[panel, rounded corners=2mm] (117,0) rectangle (170,-60);\n"
# phase headers (the three-phase pipeline described in the text), each with a thin rule
# spanning the part of the figure it covers
for num, lab, x0, x1 in [(1, "Generation", 3, 47), (2, "Evaluation", 52.5, 110)]:
    b += f"\\node[num] at ({x0+1.8},-4.2) {{{num}}};\n\\node[head] at ({x0+4.6},-4.2) {{{lab}}};\n"
    b += f"\\draw[rule, line width=0.6pt] ({x0},-6.9) -- ({x1},-6.9);\n"
b += cv_icon(10, -31) + "\\node[small, align=center, text=ink] at (10,-44.5) {\\textbf{One candidate}\\\\[0.3mm]CV + job ad};\n"
b += "\\node[tiny, align=center] at (10,-51) {$\\times$ 500 candidates\\\\(10 jobs $\\times$ 50 CVs)};\n"
b += letters(-9.5, 4.25)
b += "\\draw[arr] (47.5,-31) -- (51.9,-31);\n\\draw[arr] (70.1,-31) -- (73.5,-31);\n" + screener(61, -31)
xb, s = 94, 23
# Shaded panel starts just below the header rule (y=-6.9) so it does not cross it,
# and extends left far enough to contain the most negative dot (Llama row).
vmin = min(cl[w].drop("Avg.").min() for w in order)
left = min(-0.62, vmin - 0.06)
b += f"\\fill[penbg] ({xb+left*s:.2f},-7.6) rectangle ({xb},-54.2);\n\\fill[favbg] ({xb},-7.6) rectangle ({xb+0.68*s},-54.2);\n"
for k, w in enumerate(order):
    y = -9.5 - k * 4.25; v = cl[w].drop("Avg."); 
    b += f"\\draw[black!25, line width=1.2pt, line cap=round] ({xb+v.min()*s:.2f},{y:.2f}) -- ({xb+v.max()*s:.2f},{y:.2f});\n"
    for e, ve in v.items():
        if e == w:
            # self-evaluation: filled square in the writer colour with a dark edge, as in Fig. 2
            b += f"\\filldraw[fill={TEX[w]}, draw=ink, line width=0.35pt] ({xb+ve*s-0.95:.2f},{y-0.95:.2f}) rectangle ({xb+ve*s+0.95:.2f},{y+0.95:.2f});\n"
        else:
            b += f"\\fill[{TEX[e]}] ({xb+ve*s:.2f},{y:.2f}) circle (0.62);\n"
    b += f"\\fill[ink] ({xb+avg_cl[w]*s-0.3:.2f},{y+1.5:.2f}) rectangle ({xb+avg_cl[w]*s+0.3:.2f},{y-1.5:.2f});\n"
b += f"\\draw[ink2, line width=0.4pt] ({xb},-7.6) -- ({xb},-54.2);\n"
# x axis under the dot plot: ticks every 0.5 on the 1-10 score scale
ax_y = -54.2
right = 0.68
b += f"\\draw[ink2, line width=0.4pt] ({xb+left*s:.2f},{ax_y}) -- ({xb+right*s:.2f},{ax_y});\n"
for t in [-0.5, 0.0, 0.5]:
    if left <= t <= right:
        lab = "0" if t == 0 else f"{t:+.1f}".replace("-", "$-$")
        b += f"\\draw[ink2, line width=0.4pt] ({xb+t*s:.2f},{ax_y}) -- ({xb+t*s:.2f},{ax_y-0.7});\n"
        b += f"\\node[tiny, anchor=north] at ({xb+t*s:.2f},{ax_y-0.8}) {{{lab}}};\n"
b += f"\\node[tiny] at ({xb},-58.4) {{score gap (1--10 scale), cover letter only}};\n"
# direction labels inside the plot, in the corners the dots leave free
# (top rows sit on the favoured side, bottom rows on the penalised side)
b += f"\\node[tiny, anchor=north west] at ({xb+left*s+0.5:.2f},-8.0) {{\\textcolor{{penc}}{{$\\leftarrow$ penalised}}}};\n"
b += f"\\node[tiny, anchor=south east] at ({xb+right*s-0.5:.2f},{ax_y+0.5}) {{\\textcolor{{fav}}{{favoured $\\rightarrow$}}}};\n"
b += "\\node[num] at (121.8,-4.2) {3};\n\\node[head] at (124.6,-4.2) {Analysis};\n"
b += "\\draw[rule, line width=0.6pt] (120,-6.9) -- (167,-6.9);\n"
b += "\\node[small, align=left, anchor=north west, text=ink] at (120,-9.2) {11 writers $\\cdot$ 9 evaluators $\\cdot$ 3 conditions $\\cdot$ 4 runs\\\\\\textbf{414,000 evaluations}};\n"
b += findings_col()
open(OUT, "w").write(doc(61, b))
print("Wrote", os.path.normpath(OUT))

